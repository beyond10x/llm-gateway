//! The CLI reference page, walked from the clap definitions of `b10x-llm-gateway`: the serving
//! command line (`llm_gateway_cli::cli::Cli`) and the `credential set` command
//! (`llm_gateway_cli::cli::CredentialCli`).

use std::fmt::Write as _;

use clap::CommandFactory as _;

use crate::{GITHUB, cell, front_matter};

/// Where the CLI reference lands, relative to the repository root.
pub const PAGE: &str = "website/docs/reference/cli.md";

fn text(value: Option<&clap::builder::StyledStr>) -> String {
    value.map(ToString::to_string).unwrap_or_default()
}

/// One row per argument of `command`: how it is written, whether it is required, its default
/// and its help.
fn arguments(command: &clap::Command) -> Vec<[String; 4]> {
    command
        .get_arguments()
        .filter(|arg| !matches!(arg.get_id().as_str(), "help" | "version"))
        .map(|arg| {
            let value = arg
                .get_value_names()
                .and_then(|names| names.first().map(ToString::to_string))
                .unwrap_or_else(|| arg.get_id().as_str().to_uppercase());
            let takes_value = arg.get_num_args().is_some_and(|n| n.takes_values());
            let written = match (arg.get_long(), takes_value) {
                (Some(long), true) => format!("--{long} <{value}>"),
                (Some(long), false) => format!("--{long}"),
                (None, _) => format!("<{value}>"),
            };
            let defaults: Vec<String> = arg
                .get_default_values()
                .iter()
                .map(|default| default.to_string_lossy().into_owned())
                .filter(|default| default != "false")
                .collect();
            let mut help = cell(&text(arg.get_long_help().or(arg.get_help())));
            if !help.is_empty() && !help.ends_with('.') {
                help.push('.');
            }
            [
                format!("`{written}`"),
                if arg.is_required_set() { "yes" } else { "no" }.to_owned(),
                if defaults.is_empty() {
                    "none".to_owned()
                } else {
                    format!("`{}`", defaults.join(", "))
                },
                help,
            ]
        })
        .collect()
}

/// The CLI reference page for the command line `root`.
pub fn page_for(mut root: clap::Command) -> String {
    root.build();
    let name = root.get_name().to_owned();
    let mut out = front_matter(
        &format!("{name} command line"),
        1,
        &format!("Every option of the {name} command line, generated from its clap definition."),
    );
    let _ = write!(
        out,
        "# `{name}`\n\nGenerated by `llm-gateway-docs` from the clap definition in \
         [`crates/llm-gateway-cli/src/cli.rs`]({GITHUB}/blob/main/crates/llm-gateway-cli/src/cli.rs). \
         `{name} --help` prints the same text and `{name} --version` prints the name and the \
         package version.\n\n> {}\n\n```text\n{}\n```\n\n\
         ## Options\n\n| Option | Required | Default | Meaning |\n| --- | --- | --- | --- |\n",
        cell(&text(root.get_long_about().or(root.get_about()))),
        root.render_usage().to_string().trim_end(),
    );
    for row in arguments(&root) {
        let _ = writeln!(out, "| {} |", row.join(" | "));
    }
    out.push_str(
        "\nThe serving command line takes nothing else: a positional argument or another option is \
         a usage error. The one other command, `credential set` below, is reached only when \
         `credential` is the first argument. The document the option names is described in \
         [the deployment document](./deployment-document.md).\n\n\
         ## Exit status\n\n| Status | When | Last line on standard error |\n| --- | --- | --- |\n\
         | 0 | stopped by SIGINT or SIGTERM after every accepted request was answered | \
         `b10x-llm-gateway: stopped by <signal> accepted=<n> completed=<n>` |\n\
         | 1 | the start was refused: the document, a file it names, the listen address or the \
         signal handlers | `b10x-llm-gateway: refused <source>:<rule>: <message>` |\n\
         | 2 | a usage error, which names its kind and never echoes an argument | ``b10x-llm-gateway: usage error (<kind>); Usage: b10x-llm-gateway \
         --config <CONFIG>; see `b10x-llm-gateway --help` `` |\n\n\
         While it serves, the process writes `b10x-llm-gateway: listening on <address>` once. \
         `RUST_LOG` sets the level of the structured events it writes beside these lines \
         (default `info`).\n",
    );
    out
}

/// The section for one subcommand `leaf` of `command`: its about text, usage line and options.
fn subcommand_section(mut command: clap::Command, leaf: &str) -> String {
    command.build();
    let leaf = command
        .find_subcommand_mut(leaf)
        .expect("the command declares the subcommand")
        .clone();
    let name = format!(
        "{} {}",
        command.get_bin_name().unwrap_or(command.get_name()),
        leaf.get_name()
    );
    let mut leaf = leaf.bin_name(&name);
    let mut out = format!(
        "\n## `{name}`\n\n> {}\n\n```text\n{}\n```\n\n\
         | Option | Required | Default | Meaning |\n| --- | --- | --- | --- |\n",
        cell(&text(leaf.get_long_about().or(leaf.get_about()))),
        leaf.render_usage().to_string().trim_end(),
    );
    for row in arguments(&leaf) {
        let _ = writeln!(out, "| {} |", row.join(" | "));
    }
    out
}

/// The CLI reference page for `b10x-llm-gateway`.
pub fn page() -> String {
    let mut out = page_for(llm_gateway_cli::cli::Cli::command());
    out.push_str(&subcommand_section(
        llm_gateway_cli::cli::CredentialCli::command(),
        "set",
    ));
    out.push_str(
        "\nExactly one of `--model` and `--route` is required. The key is never an argument or \
         an environment variable: it is read from a hidden prompt on the terminal, or from \
         standard input with `--stdin`, one line whose newline is not part of it. On success the \
         command writes one line, `b10x-llm-gateway: credential stored <path> probe \
         <passed|skipped|not-rejected> http <code|->`, and exits 0; a refusal is \
         `b10x-llm-gateway: refused <code>: <message>` with exit status 1 and writes nothing \
         ([the refusal reference](./refusals.md#credential-refusals)); a usage error names its kind and never echoes an argument, \
         exit status 2. [Store an upstream key](../guides/store-an-upstream-key.md) walks \
         through it.\n",
    );
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_one_option_and_the_usage_line_are_listed() {
        let page = page();
        assert!(page.contains(crate::HEADER));
        assert!(page.contains("custom_edit_url: null"));
        assert!(page.contains("Usage: b10x-llm-gateway --config <CONFIG>"));
        assert!(page.contains("| `--config <CONFIG>` | yes | none |"));
        assert!(!page.contains("`--help`"), "help and version are not rows");
        assert!(page.contains("## `b10x-llm-gateway credential set`"));
        assert!(page.contains("| `--model <ALIAS>` | no | none |"));
        assert!(page.contains("| `--no-probe` | no | none |"));
    }
}
